/**
 * **전선 계약** — 판정 주체(로컬 룰 엔진이든 서버든)가 보내는 것의 모양 (GDD §10).
 *
 * ```
 * 클라 → 판정 주체   의도(Intent) 하나            ← 판정 결과는 절대 안 보낸다
 * 판정 주체 → 클라   { 로그를 뺀 스냅샷, 이벤트[], 남은 ms }
 * ```
 *
 * ────────────────────────────────────────────────────────────────
 * 왜 `rules`에 있나 — **재는 주체가 둘이 됐다**
 * ────────────────────────────────────────────────────────────────
 *
 * H1에서는 이 계약이 클라이언트에만 있었다. 저편에 아무도 없었으니 당연했다.
 * H2에서 `packages/server`가 생기면서 **같은 모양을 양쪽이 알아야** 하고, 그러면
 * 어느 한쪽에 두는 순간 다른 쪽이 **베껴 적는다** — `timing.ts`를 여기로 올린 것과
 * 정확히 같은 이유다(상수가 두 벌이면 어긋나도 화면은 아무 말도 안 한다).
 *
 * **떼는 자리(`toWire`)와 붙이는 자리(`applyWire`)는 여전히 각각 하나**다.
 *
 * ────────────────────────────────────────────────────────────────
 * 로그를 뺀다 ★ — 전선의 `O(턴²)`
 * ────────────────────────────────────────────────────────────────
 *
 * | | 스냅샷(로그 제외) | 로그 포함 | 턴 |
 * |---|---:|---:|---:|
 * | 3v3 | **2,408 B** | 27,743 B | 48 |
 * | 5v5 | **3,705 B** | 55,089 B | 104 |
 *
 * 로그를 실으면 **한 통이 판 길이에 비례해 커진다** — 매 턴 보내므로 전선에서
 * `O(턴²)`다. 뗀 로그는 받는 쪽이 이벤트를 이어 붙여 되만들고, 그게 정확히 같은
 * 것은 엔진이 보장한다(`이전 로그 ++ events === 다음 로그`).
 *
 * **이벤트만 보내는 길은 안 골랐다** — 리듀서가 없고, 만들면 `apply()`의 두 번째
 * 구현이다. **재접속도 이 결정에 딸려 풀린다**: 돌아온 사람에게는 지금 스냅샷 한 통이면 된다.
 */

import type { BattleEvent, BattleState, Side } from './types.ts';

/** 로그를 뺀 상태. **전선에 실리는 것은 언제나 이 모양이다** */
export type BattleStateWire = Omit<BattleState, 'log'>;

/**
 * 방이 접힌 사연과 그 정산 (GDD §3.9 이탈 표 · §5-64~68).
 *
 * **성립하지 않은 판**(배치 중 이탈 · 양쪽 이탈 · 양쪽 유휴)에만 실린다.
 * 정찰 이후의 이탈은 서버가 사라진 쪽 대신 `surrender`를 적용하므로 **여기 안 온다** —
 * 엔진이 낸 평범한 결말이고 보상표(§6.4)가 그대로 걸린다.
 *
 * ⚠ **H2에서는 이 지시를 클라이언트가 그대로 믿고 제 계정에 적용한다.** 계정이 아직
 * 브라우저에 있어서다(§5-61) — 서버가 재검증하는 것은 H3다. 아는 채로 둔다.
 */
export interface RoomClose {
  /** `left` 재접속 유예를 넘겨 안 돌아왔다 · `idle` 방 유휴 상한 2분 */
  reason: 'left' | 'idle';
  /**
   * 참가비를 **돌려받는** 진영.
   *
   * **사라진 쪽은 여기 안 들어간다** — 돌려주면 참가비를 낸 뒤 끊어서 회피할 수
   * 있고, 그러면 「다시 찾기」(군량 −1)가 통째로 무력해진다(§5-65).
   * **끊는 것이 거절보다 싸지면 안 된다.**
   */
  refund: Side[];
}

/**
 * 판정 주체가 보내는 것. **로컬이든 온라인이든 같은 모양이다.**
 *
 * 갈래가 `sync` 하나뿐인 것은 일부러다 — **부를 자리가 없는 갈래는 도는 적이
 * 없다**(§5-52). 「의도가 거부됐다」는 로컬에서 우리 UI의 버그라 던져서 알리고,
 * 서버에서는 조용히 버린다(믿을 수 없는 클라이언트에게 설명할 이유가 없다).
 */
export interface ServerMsg {
  t: 'sync';
  /** 로그를 뺀 지금 상태 */
  state: BattleStateWire;
  /** 이번에 일어난 일. 받는 쪽이 **제 로그에 이어 붙인다** */
  events: BattleEvent[];
  /**
   * 지금 단계가 끝나기까지 **남은 ms**. `null`이면 마감이 없다.
   *
   * **절대시각이 아니라 남은 시간이다** — 서버와 사람의 시계는 몇 초씩 어긋나 있고,
   * 절대시각을 그대로 실으면 그 어긋남이 카운트다운에 고스란히 나온다. 받는 쪽이
   * 제 시계로 `지금 + 남은 ms`를 만든다. **단계가 바뀔 때만 다시 잰다.**
   *
   * 제어 단계에서는 이 값이 **`[차례 넘기기]`가 열리는 시각**이다(온라인만) —
   * 20초를 재는 자리가 화면에 하나 더 있으면 상수가 두 벌이 된다.
   */
  deadlineInMs: number | null;
  /**
   * 방이 접혔다 — **성립하지 않은 판**이다. 전적도 보상도 없고 정산만 있다.
   *
   * 있으면 이 통이 마지막이고, 받는 쪽은 곧바로 결말로 간다.
   */
  close?: RoomClose;
}

/**
 * 로그를 뗀다. **한 군데서만** 뗀다 — 두 군데면 한쪽이 언젠가 안 뗀다.
 *
 * ────────────────────────────────────────────────────────────────
 * 전선의 `phase`는 **받는 사람의 걸음**이다 ★ — `waiting`이 사는 자리
 * ────────────────────────────────────────────────────────────────
 *
 * 「나는 배치를 마쳤고 상대를 기다린다」는 **한쪽만의 사실**이라 공유 상태의
 * `phase`에 넣을 수 없다 — 넣으면 아직 배치 중인 상대가 판을 못 만진다.
 * 그래서 권위 상태는 `deploy` 그대로 두고 **떼면서 관점을 넣는다.**
 *
 * | `state.ready[받는 쪽]` | 전선의 phase | 재생기의 걸음 | 마감 |
 * |---|---|---|---|
 * | `false` | `deploy` | `deploying` | `DEPLOY_MS` 잔여 |
 * | `true` | **`waiting`** | `aiThinking` | `WAITING_MS` 잔여 |
 *
 * 이렇게 두면 `BattlePhase` 하나가 재생기의 걸음 하나로 곧게 떨어진다 —
 * 「`phase`는 화면이 읽는 값이라 거짓말을 하면 안 된다」의 짝이다.
 * **오프라인에서는 여전히 한 번도 안 나타난다**: 상대(AI)가 `open()`에서 곧바로
 * 준비를 마치므로 사람이 언제나 마지막에 누른다.
 *
 * `side`가 `null`이면 관점이 없다(관전·회귀) — 권위 상태 그대로 나간다.
 */
export function toWire(state: BattleState, side: Side | null = null): BattleStateWire {
  const { log: _log, ...wire } = state;
  if (side && wire.phase === 'deploy' && wire.ready[side]) wire.phase = 'waiting';
  return wire;
}

/**
 * 받은 통을 지금 상태로 되만든다 — **로그를 이어 붙이는 유일한 자리.**
 *
 * `이전 로그 ++ events === 보낸 쪽의 로그`가 성립한다(엔진의 `commit()` 계약).
 */
export function applyWire(prev: BattleState, msg: ServerMsg): BattleState {
  return { ...msg.state, log: prev.log.concat(msg.events) } as BattleState;
}
