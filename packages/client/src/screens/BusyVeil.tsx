/**
 * 서버 왕복 중에 덮는 가리개 (2026-09-04).
 *
 * ────────────────────────────────────────────────────────────────
 * 왜 필요한가 — 「멈춘 것」과 「기다리는 것」은 다르다
 * ────────────────────────────────────────────────────────────────
 *
 * 자재 구매·도시 증축·건물 짓기는 이제 **판정을 서버가 한다**(`POST /market/materials`·
 * `/city/*`). 로컬 계산이던 시절에는 즉시 바뀌던 화면이 이제 한 왕복만큼 가만히
 * 있는데, 화면에는 **아무 신호도 없어 「눌렀는데 아무 일이 없다」로 읽힌다** —
 * 이 저장소가 「눌리는데 아무 일도 없으면 「고장인가」가 남는다」로 여러 번 적어 둔
 * 그 자리다. 단추를 잠그는 것(`busy`)은 두 번 눌리는 것만 막지 그 사실을 말하지는
 * 않는다.
 *
 * ────────────────────────────────────────────────────────────────
 * 규약 셋
 * ────────────────────────────────────────────────────────────────
 *
 * 1. **프레임 안을 덮는다.** `.modal-back`과 같은 `position: absolute; inset: 0`이라
 *    (`ScreenChrome`의 `.scr`이 기준점) 브라우저 창이 아니라 게임 화면만 가린다.
 * 2. **입력을 막는다** — 가리개가 클릭을 먹는다. 왕복 중에 다른 단추가 눌리면
 *    「두 번 누르면 기회를 두 번 쓴다」가 다른 경로로 되살아난다.
 * 3. **말이 붙는다.** 「무엇을 기다리는가」를 적는다 — 도는 그림만 있으면 무엇이
 *    걸린 것인지 알 수 없고, 그건 오래 걸릴 때 특히 나쁘다.
 *
 * **뜨는 데 뜸을 들인다** — `data-late`가 붙기 전(=`SHOW_AFTER_MS` 안에 끝나면)에는
 * 투명하다. 서버가 가까우면 왕복이 수십 ms인데, 그때마다 가리개가 번쩍이면
 * 그게 더 고장처럼 보인다. **막는 일은 처음부터** 하고 **보이는 것만** 늦춘다.
 */

import { t } from '../i18n/index.ts';

/** 이만큼 지나도 안 끝나면 그때 보인다. 그 전에는 투명한 채로 입력만 막는다 */
const SHOW_AFTER_MS = 180;

export function BusyVeil({ label }: {
  /** 무엇을 기다리는가. 없으면 기본 문구 */
  label?: string;
}): React.JSX.Element {
  return (
    <div
      className="busy-veil"
      data-modal="busy"
      style={{ animationDelay: `${SHOW_AFTER_MS}ms` }}
      role="status"
      aria-live="polite"
      onClick={(e) => e.stopPropagation()}
    >
      <div className="busy-box">
        {/* 도는 그림은 CSS만으로 그린다 — 새 에셋을 만들지 않는다.
            「움직임 줄이기」를 켠 사람에게는 안 돌고 글자만 남는다(style.css) */}
        <span className="busy-spin" aria-hidden="true" />
        <span className="busy-lbl">{label ?? t('busy.wait')}</span>
      </div>
    </div>
  );
}
