/**
 * 화면 배경의 미세한 움직임 — 「살아 있는 그림」 (2026-08-15)
 *
 * 배경이 완전히 멈춰 있으면 정지 화면처럼 보인다. 몇 초에 한 번씩 아주 조금
 * 밀고 당겨 주면 그림이 숨 쉬는 것처럼 읽힌다. 영상 편집에서 말하는 켄 번스와
 * 같은 결이지만, **쉬지 않고 흐르는 대신 자세를 하나씩 짚고 간다** —
 * 기획자 지정이 「2~3초 간격으로 약간씩」이라서다.
 *
 * ────────────────────────────────────────────────────────────────
 * 여기는 순수 함수다 — 시계도 난수도 없다
 * ────────────────────────────────────────────────────────────────
 *
 * `backdrop.ts`가 시계를 밖에서 받는 것과 같은 이유다. 자세를 난수로 고르면
 * 「그림이 화면 밖으로 삐져나오는 자세」가 어쩌다 한 번 나오고, 그건 눈으로
 * 재현할 수 없다. 여기서는 **정해진 여덟 자세를 돌 뿐**이고, 몇 번째 자세인지는
 * 부르는 쪽(`useBackdropDrift`)이 넣는다.
 *
 * ────────────────────────────────────────────────────────────────
 * 확대(`DRIFT_ZOOM`)는 장식이 아니라 **안전 여백**이다 ★
 * ────────────────────────────────────────────────────────────────
 *
 * 배율 1인 그림을 옆으로 밀면 반대쪽에 **바탕색 띠가 드러난다.** 먼저 조금
 * 키워 두고 그 안에서만 움직여야 한다. 키운 만큼 한쪽에 `(s−1)/2`의 여유가
 * 생기므로 **밀어내는 거리가 그보다 작아야** 한다 — 이 부등식을
 * `test/backdrop.test.ts`가 자세마다 확인한다. 화면에서는 「끝에 이상한 줄이
 * 있네」로만 보이는 종류의 어긋남이라 눈으로 잡기 어렵다.
 */

/** 한 자세에 머무는 시간(ms). 기획자 지정 「2초나 3초」의 가운데. */
export const DRIFT_MS = 2600;

/** 밑바탕 확대율. 위 주석의 안전 여백 — 한쪽에 3%가 남는다. */
export const DRIFT_ZOOM = 1.06;

/** 자세 하나. `x`·`y`는 그림 크기 대비 %, `z`는 `DRIFT_ZOOM`에 곱하는 배율. */
export interface DriftPose {
  x: number;
  y: number;
  z: number;
}

/**
 * 도는 자세들. 시계 방향으로 한 바퀴 돌면서 배율이 완만하게 부풀었다 꺼진다 —
 * 밀기만 하면 「미끄러진다」로 보이고, 배율이 같이 움직여야 「다가온다」가 된다.
 *
 * 마지막 자세에서 첫 자세로 돌아가는 것도 이어지는 한 걸음이다(둘 다 원점 근처).
 * 여덟 자세 × 2.6초 = 한 바퀴 약 21초.
 */
export const DRIFT_PATH: readonly DriftPose[] = [
  { x: 0.0, y: 0.0, z: 1.000 },
  { x: 0.9, y: -0.5, z: 1.006 },
  { x: 1.5, y: 0.4, z: 1.012 },
  { x: 0.6, y: 1.1, z: 1.018 },
  { x: -0.5, y: 1.2, z: 1.012 },
  { x: -1.5, y: 0.3, z: 1.006 },
  { x: -1.2, y: -0.9, z: 1.000 },
  { x: -0.2, y: -1.2, z: 1.006 },
];

/**
 * 몇 번째 걸음인가 → 자세. 걸음 수는 계속 늘어나므로 나머지로 감는다.
 *
 * **걸음 수를 0으로 되돌리지 않는 이유** — 되돌리는 순간 그 한 번만 이동
 * 거리가 커져 그림이 튄다. 늘어나는 정수를 그대로 두고 여기서만 접는다.
 */
export function driftPose(step: number): DriftPose {
  const n = DRIFT_PATH.length;
  return DRIFT_PATH[((step % n) + n) % n]!;
}

/**
 * 자세 → CSS `transform`.
 *
 * **`scale`을 먼저 적는다.** `translate`의 %는 그림 제 크기 기준인데, 순서를
 * 뒤집으면 밀어내는 거리가 배율만큼 커지거나 작아진다 — 위의 안전 여백 계산과
 * 어긋나게 하지 않으려면 한쪽으로 고정해 두는 편이 낫다(테스트가 이 순서를 전제한다).
 */
export function driftTransform(step: number): string {
  const p = driftPose(step);
  return `scale(${(DRIFT_ZOOM * p.z).toFixed(4)}) translate(${p.x}%, ${p.y}%)`;
}
